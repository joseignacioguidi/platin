import { CardCycle, statementDatesFor, statementPeriodFor, StatementOverrides } from './card-cycle';
import { addMonths, compareDates, LocalDate, Period, periodOf } from './dates';
import { Currency, FixedKind } from './enums';
import { CurrencyTotals, RatesInput, totalsByCurrency } from './exchange';
import { Money } from './money';
import { duePeriods, FixedSchedule } from './fixed';

/** An installment of a statement, shown as detail of what the statement commits (COM-03). */
export interface StatementInstallment {
  chargeId: string;
  description: string;
  number: number;
  count: number;
  amount: Money;
}

/** A statement that is not paid yet, with what is still pending in each currency. */
export interface StatementCommitment {
  statementId: string;
  cardId: string;
  dueDate: LocalDate;
  /** Total − paid, per currency (zero amounts are skipped). */
  pending: readonly Money[];
  /** Whether part of it was already paid. */
  partiallyPaid: boolean;
  installments: readonly StatementInstallment[];
}

export interface FixedCommitment extends FixedSchedule {
  id: string;
  name: string;
  /** Set for fixed items charged to a card (TAR-09): they fall into that card's statements. */
  cardId?: string | null;
}

/** A card's cycle, with the statement dates corrected by hand. */
export interface CardCommitmentCycle extends CardCycle {
  id: string;
  overrides?: StatementOverrides;
}

/** The movement a fixed item on a pocket already generated for a period. */
export interface FixedOccurrence {
  fixedId: string;
  period: Period;
  confirmed: boolean;
  /** Its amount: a pending one may have been corrected. */
  amount: Money;
}

/** MOV-08: an income or expense scheduled for a future date, not confirmed yet. */
export interface ScheduledCommitment {
  id: string;
  kind: 'INCOME' | 'EXPENSE';
  date: LocalDate;
  amount: Money;
  description: string;
}

export interface CommitmentsInput {
  /** Unpaid statements (the caller leaves out paid ones). */
  statements: readonly StatementCommitment[];
  /** Fixed items on a pocket or on a card (income and expense). */
  fixed: readonly FixedCommitment[];
  /** Cycles of the cards that fixed items are charged to. */
  cards?: readonly CardCommitmentCycle[];
  /** Movements already generated by fixed items on a pocket. */
  fixedOccurrences?: readonly FixedOccurrence[];
  /** `${fixedId}|${period}` of card charges already generated by a fixed item on a card. */
  fixedCharges?: ReadonlySet<string>;
  /** Pending scheduled movements. */
  scheduled?: readonly ScheduledCommitment[];
  base: Currency;
  /** Rates (pesos per unit) used to value everything in the base currency. */
  rates: RatesInput;
}

export type CommitmentItem =
  | {
      type: 'STATEMENT';
      date: LocalDate;
      amount: Money;
      statementId: string;
      cardId: string;
      partiallyPaid: boolean;
      installments: readonly StatementInstallment[];
    }
  | {
      type: 'FIXED';
      date: LocalDate;
      amount: Money;
      fixedId: string;
      name: string;
      cardId: string | null;
    }
  | {
      type: 'SCHEDULED';
      date: LocalDate;
      amount: Money;
      scheduledId: string;
      description: string;
    };

export interface MonthCommitments {
  period: Period;
  committed: CurrencyTotals;
  /** Fixed incomes + scheduled incomes of the month. */
  expectedIncome: CurrencyTotals;
  /** Expected income − committed, in base currency. */
  free: Money;
  items: CommitmentItem[];
}

const key = (fixedId: string, period: Period) => `${fixedId}|${period}`;

/**
 * COM-01/02, the one rule of what is committed in a month, for Compromisos and the home screen.
 * Committed in month M =
 * - the pending part of the unpaid statements due in M (installments, charges and adjustments
 *   minus what was paid);
 * - fixed expenses on a pocket due in M that are not confirmed (a generated pending movement
 *   counts with its own amount);
 * - fixed expenses on a card whose charge for that period doesn't exist yet, in the month their
 *   statement is due (once generated, the charge is part of its statement);
 * - scheduled expenses of M.
 * Expected income = fixed incomes of M + scheduled incomes of M.
 */
export function commitmentsByMonth(
  input: CommitmentsInput,
  from: Period,
  months: number,
): MonthCommitments[] {
  if (!Number.isInteger(months) || months < 1) throw new Error('months must be at least 1');
  const to = addMonths(from, months - 1);
  const occurrences = new Map(
    (input.fixedOccurrences ?? []).map((o) => [key(o.fixedId, o.period), o]),
  );
  const charged = input.fixedCharges ?? new Set<string>();
  const cards = new Map((input.cards ?? []).map((card) => [card.id, card]));

  const fixedItems = new Map<Period, CommitmentItem[]>();
  const incomes = new Map<Period, Money[]>();
  const push = <T>(map: Map<Period, T[]>, period: Period, value: T) =>
    map.set(period, [...(map.get(period) ?? []), value]);

  for (const fixed of input.fixed) {
    if (fixed.cardId) {
      if (fixed.kind !== FixedKind.EXPENSE) continue;
      const card = cards.get(fixed.cardId);
      if (!card) continue;
      // A charge late in a month can be due two months later: look back two months.
      for (const due of duePeriods(fixed, addMonths(from, -2), to)) {
        if (charged.has(key(fixed.id, due.period))) continue;
        const statement = statementPeriodFor(card, due.date, card.overrides);
        const { dueDate } = statementDatesFor(card, statement, card.overrides);
        const month = periodOf(dueDate);
        if (month < from || month > to) continue;
        push(fixedItems, month, {
          type: 'FIXED',
          date: dueDate,
          amount: due.amount,
          fixedId: fixed.id,
          name: fixed.name,
          cardId: fixed.cardId,
        });
      }
      continue;
    }
    for (const due of duePeriods(fixed, from, to)) {
      const occurrence = occurrences.get(key(fixed.id, due.period));
      const amount = occurrence?.amount ?? due.amount;
      if (fixed.kind === FixedKind.INCOME) {
        push(incomes, due.period, amount);
      } else if (!occurrence?.confirmed) {
        push(fixedItems, due.period, {
          type: 'FIXED',
          date: due.date,
          amount,
          fixedId: fixed.id,
          name: fixed.name,
          cardId: null,
        });
      }
    }
  }

  return Array.from({ length: months }, (_, i) => {
    const period = addMonths(from, i);
    const statementItems: CommitmentItem[] = input.statements
      .filter((statement) => periodOf(statement.dueDate) === period)
      .flatMap((statement) =>
        statement.pending
          .filter((amount) => !amount.isZero())
          .map((amount) => ({
            type: 'STATEMENT' as const,
            date: statement.dueDate,
            amount,
            statementId: statement.statementId,
            cardId: statement.cardId,
            partiallyPaid: statement.partiallyPaid,
            installments: statement.installments.filter(
              (installment) => installment.amount.currency === amount.currency,
            ),
          })),
      );
    const scheduled = (input.scheduled ?? []).filter((s) => periodOf(s.date) === period);
    const scheduledItems: CommitmentItem[] = scheduled
      .filter((s) => s.kind === 'EXPENSE')
      .map((s) => ({
        type: 'SCHEDULED',
        date: s.date,
        amount: s.amount,
        scheduledId: s.id,
        description: s.description,
      }));

    const items = [...statementItems, ...(fixedItems.get(period) ?? []), ...scheduledItems].sort(
      (a, b) => compareDates(a.date, b.date),
    );
    const committed = totalsByCurrency(
      items.map((item) => item.amount),
      input.base,
      input.rates,
    );
    const expectedIncome = totalsByCurrency(
      [
        ...(incomes.get(period) ?? []),
        ...scheduled.filter((s) => s.kind === 'INCOME').map((s) => s.amount),
      ],
      input.base,
      input.rates,
    );
    return {
      period,
      committed,
      expectedIncome,
      free: expectedIncome.base.subtract(committed.base),
      items,
    };
  });
}
