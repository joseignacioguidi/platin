// Writes build-time settings for the web app from environment variables.
// Run by the `web:write-env` target before build, serve, test and typecheck.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const apiDirectUrl = (process.env.API_DIRECT_URL ?? '').replace(/\/$/, '');

const content = `// Generated by apps/web/scripts/write-env.mjs. Do not edit.\n` +
  `export const API_DIRECT_URL = ${JSON.stringify(apiDirectUrl)};\n`;

writeFileSync(resolve(here, '../src/env.generated.ts'), content);
