import { HttpStatus, Injectable } from '@nestjs/common';
import type {
  ChangeFixedAmountRequest,
  CreateFixedRequest,
  FixedItem,
  UpdateFixedRequest,
} from '@platin/contracts';
import { addMonths, maxDate, Money, parsePeriod, periodOf, utcToPeriod } from '@platin/domain';
import { PocketsService } from '../accounts/pockets.service';
import { CategoriesService } from '../categories/categories.service';
import { AppException } from '../common/app-exception';
import { ClockService } from '../common/clock.service';
import { toDbPeriod } from '../common/serialize';
import { PrismaService } from '../prisma/prisma.service';
import { FIXED_INCLUDE, FixedRow, toFixedDto } from './fixed.mapper';

/** FIJ-01..03. Pending movements are generated by SyncService when the app opens (FIJ-04). */
@Injectable()
export class FixedService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly pockets: PocketsService,
    private readonly categories: CategoriesService,
    private readonly clock: ClockService,
  ) {}

  async list(userId: string): Promise<FixedItem[]> {
    const rows = await this.prisma.fixedItem.findMany({
      where: { userId },
      include: FIXED_INCLUDE,
      orderBy: [{ kind: 'asc' }, { dayOfMonth: 'asc' }],
    });
    const current = periodOf(this.clock.today());
    return rows.map((row) => toFixedDto(row, current));
  }

  async get(userId: string, id: string): Promise<FixedItem> {
    return toFixedDto(await this.getOwned(userId, id), periodOf(this.clock.today()));
  }

  async create(userId: string, request: CreateFixedRequest): Promise<FixedItem> {
    const pocket = await this.pockets.getActive(userId, request.pocketId);
    await this.categories.getOwned(userId, request.categoryId, request.kind);
    const row = await this.prisma.fixedItem.create({
      data: {
        userId,
        kind: request.kind,
        name: request.name,
        categoryId: request.categoryId,
        pocketId: pocket.id,
        currency: pocket.currency,
        intervalMonths: request.intervalMonths ?? 1,
        dayOfMonth: request.dayOfMonth,
        startPeriod: toDbPeriod(parsePeriod(request.startPeriod)),
        endPeriod: request.endPeriod ? toDbPeriod(parsePeriod(request.endPeriod)) : null,
        amounts: {
          create: {
            amount: Money.of(request.amount, pocket.currency).toString(),
            effectiveFrom: toDbPeriod(parsePeriod(request.startPeriod)),
          },
        },
      },
      include: FIXED_INCLUDE,
    });
    return toFixedDto(row, periodOf(this.clock.today()));
  }

  async update(userId: string, id: string, changes: UpdateFixedRequest): Promise<FixedItem> {
    const row = await this.getOwned(userId, id);
    if (changes.categoryId) await this.categories.getOwned(userId, changes.categoryId, row.kind);
    if (changes.pocketId) {
      const pocket = await this.pockets.getActive(userId, changes.pocketId);
      if (pocket.currency !== row.currency) {
        throw new AppException(
          'FIXED_CURRENCY_MISMATCH',
          HttpStatus.UNPROCESSABLE_ENTITY,
          'The new pocket must be in the same currency',
        );
      }
    }
    const { paused, endPeriod, ...rest } = changes;
    const current = periodOf(this.clock.today());
    const updated = await this.prisma.fixedItem.update({
      where: { id },
      data: {
        ...rest,
        ...(endPeriod === undefined ? {} : { endPeriod: endPeriod ? toDbPeriod(endPeriod) : null }),
        ...(paused === undefined ? {} : this.pauseChange(row, paused, current)),
      },
      include: FIXED_INCLUDE,
    });
    return toFixedDto(updated, current);
  }

  /**
   * FIJ-02: the new amount applies from a period on. Pending movements already generated for
   * those periods take the new amount; confirmed ones and earlier periods keep theirs.
   */
  async changeAmount(
    userId: string,
    id: string,
    request: ChangeFixedAmountRequest,
  ): Promise<FixedItem> {
    const row = await this.getOwned(userId, id);
    const amount = Money.of(request.amount, row.currency).toString();
    const from = toDbPeriod(request.effectiveFrom);
    await this.prisma.$transaction(async (tx) => {
      await tx.fixedAmount.upsert({
        where: { fixedId_effectiveFrom: { fixedId: id, effectiveFrom: from } },
        create: { fixedId: id, amount, effectiveFrom: from },
        update: { amount },
      });
      await tx.transaction.updateMany({
        where: { fixedId: id, status: 'PENDING', fixedPeriod: { gte: from }, rateToBase: 1 },
        data: { amount, baseAmount: amount },
      });
      await tx.transaction.updateMany({
        where: {
          fixedId: id,
          status: 'PENDING',
          fixedPeriod: { gte: from },
          NOT: { rateToBase: 1 },
        },
        data: { amount },
      });
    });
    return this.get(userId, id);
  }

  async remove(userId: string, id: string): Promise<void> {
    await this.getOwned(userId, id);
    const used = await this.prisma.transaction.count({
      where: { fixedId: id, status: 'CONFIRMED' },
    });
    if (used > 0) {
      throw new AppException(
        'FIXED_HAS_HISTORY',
        HttpStatus.CONFLICT,
        'It already generated confirmed movements: finish it instead of deleting it',
      );
    }
    await this.prisma.$transaction([
      this.prisma.transaction.deleteMany({ where: { fixedId: id } }),
      this.prisma.fixedItem.delete({ where: { id } }),
    ]);
  }

  /**
   * Pausing stops generation from the current month. Resuming doesn't back-fill the paused
   * months: generation continues from the current month.
   */
  private pauseChange(row: FixedRow, paused: boolean, current: ReturnType<typeof periodOf>) {
    // Stored as the first day of the current month (Buenos Aires), so the paused period is exact.
    if (paused) return row.pausedAt ? {} : { pausedAt: toDbPeriod(current) };
    if (!row.pausedAt) return {};
    const last = row.lastGeneratedPeriod ? utcToPeriod(row.lastGeneratedPeriod) : null;
    const resumeAfter = addMonths(current, -1);
    return {
      pausedAt: null,
      lastGeneratedPeriod: toDbPeriod(last ? maxDate(last, resumeAfter) : resumeAfter),
    };
  }

  private async getOwned(userId: string, id: string): Promise<FixedRow> {
    const row = await this.prisma.fixedItem.findFirst({
      where: { id, userId },
      include: FIXED_INCLUDE,
    });
    if (!row) throw AppException.notFound('Fixed item not found');
    return row;
  }
}
